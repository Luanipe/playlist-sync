#!/usr/bin/env python3
"""Mirror pending `docs/ROADMAP.md` tasks as GitHub issues (idempotent).

The roadmap stays the source of truth. This helper:

* parses every task (`P<phase>-T<n>`) and its phase, files, dependencies and DoD;
* creates one issue per pending task, titled `P<phase>-T<n> — <title>`;
* labels issues with `roadmap` and `phase-<n>`;
* (re)generates `docs/ISSUES.md` with the task -> issue mapping.

It never closes, renames or deletes anything. Run it after changing the roadmap.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROADMAP = ROOT / "docs" / "ROADMAP.md"
ISSUES_DOC = ROOT / "docs" / "ISSUES.md"

TASK_RE = re.compile(
    r"^- \[(?P<status>[ x])\] \*\*(?P<id>P\d+-T\d+) — (?P<title>.+?)\*\* "
    r"\((?P<meta>.+)\)\s*$"
)
TASK_LIKE_RE = re.compile(r"^- \[[ x]\] \*\*P\d+-T\d+")
PHASE_RE = re.compile(r"^## Phase (?P<number>\d+) — (?P<title>.+?)\s*$")
REMOTE_RE = re.compile(r"github\.com[:/](?P<owner>[^/]+)/(?P<repo>[^/]+?)(?:\.git)?$")
ROADMAP_MARKER_RE = re.compile(r"playlist-sync-roadmap-task: (?P<id>P\d+-T\d+)")

LABEL_COLOR = "5319e7"
PHASE_COLORS = (
    "0e8a16",
    "1d76db",
    "fbca04",
    "d93f0b",
    "5319e7",
    "006b75",
    "b60205",
    "c2e0c6",
    "f9d0c4",
)


@dataclass(slots=True)
class Task:
    """A roadmap task parsed from Markdown."""

    id: str
    title: str
    phase: int
    phase_title: str
    files: str
    deps: str
    done: bool
    details: list[str] = field(default_factory=list)


def parse_roadmap(text: str) -> list[Task]:
    """Parse roadmap tasks, including their indented DoD/notes."""
    tasks: list[Task] = []
    phase = 0
    phase_title = ""
    current: Task | None = None

    for raw_line in text.splitlines():
        line = raw_line.rstrip()

        phase_match = PHASE_RE.match(line)
        if phase_match:
            phase = int(phase_match.group("number"))
            phase_title = phase_match.group("title")
            current = None
            continue

        task_match = TASK_RE.match(line)
        if task_match:
            files, _, deps = task_match.group("meta").partition("; deps:")
            current = Task(
                id=task_match.group("id"),
                title=task_match.group("title"),
                phase=phase,
                phase_title=phase_title,
                files=files.strip(),
                deps=deps.strip() or "—",
                done=task_match.group("status") == "x",
            )
            tasks.append(current)
            continue

        if TASK_LIKE_RE.match(line):
            raise ValueError(f"malformed roadmap task line: {line!r}")

        if current is None:
            continue

        if line.startswith("  - "):
            current.details.append(line[4:].strip())
        elif line.startswith("    ") and line.strip():
            if current.details:
                current.details[-1] = f"{current.details[-1]} {line.strip()}"
        elif line == "":
            continue
        else:
            current = None

    return tasks


def parse_repo_slug(remote: str) -> str:
    """Return `owner/repo` from a GitHub remote URL."""
    match = REMOTE_RE.search(remote.strip())
    if not match:
        raise ValueError(f"cannot parse a GitHub repository from remote: {remote!r}")
    return f"{match.group('owner')}/{match.group('repo')}"


def issue_title(task: Task) -> str:
    return f"{task.id} — {task.title}"


def issue_body(task: Task, repo_url: str) -> str:
    details = "\n".join(f"- {entry}" for entry in task.details) or "_No extra details._"
    return f"""<!-- playlist-sync-roadmap-task: {task.id} -->
## {task.id} — {task.title}

**Phase:** {task.phase} — {task.phase_title}
**Files:** {task.files or "—"}
**Depends on:** {task.deps}

**Roadmap:** {repo_url}/blob/main/docs/ROADMAP.md

### Definition of done

{details}

---
_Generated from `docs/ROADMAP.md` by `scripts/sync_roadmap_issues.py`. The roadmap is the source \
of truth; update it before changing scope._
"""


def render_issues_doc(tasks: list[Task], issues: dict[str, int], repo_url: str) -> str:
    lines = [
        "# Roadmap ↔ GitHub issues",
        "",
        "Generated by `scripts/sync_roadmap_issues.py`. **Do not edit by hand.**",
        "The roadmap is the source of truth; each pending task maps 1:1 to an issue titled",
        "`P<phase>-T<n> — <title>`.",
        "",
        "| Task | Phase | Status | Issue |",
        "|---|---|---|---|",
    ]
    for task in tasks:
        status = "done" if task.done else "todo"
        number = issues.get(task.id)
        issue = f"[#{number}]({repo_url}/issues/{number})" if number else "—"
        lines.append(f"| `{task.id}` — {task.title} | {task.phase} | {status} | {issue} |")
    lines.append("")
    return "\n".join(lines)


def run_gh(*args: str) -> str:
    result = subprocess.run(
        ["gh", *args],
        check=True,
        text=True,
        capture_output=True,
    )
    return result.stdout.strip()


def resolve_repo_slug(
    origin_remote: str | None,
    explicit: str | None,
    *,
    allow_foreign: bool = False,
) -> str:
    """Resolve the target repository, refusing to write to a foreign repo by accident."""
    origin = parse_repo_slug(origin_remote) if origin_remote else None
    if explicit and origin and explicit != origin and not allow_foreign:
        raise ValueError(
            f"--repo {explicit!r} does not match origin {origin!r}; "
            "pass --allow-foreign-repo to override"
        )
    if explicit:
        return explicit
    if origin:
        return origin
    raise ValueError("no --repo given and no origin remote found")


def get_repo_slug(explicit: str | None, *, allow_foreign: bool = False) -> str:
    try:
        remote = subprocess.run(
            ["git", "remote", "get-url", "origin"],
            check=True,
            text=True,
            capture_output=True,
        ).stdout
    except subprocess.CalledProcessError:
        remote = None
    return resolve_repo_slug(remote, explicit, allow_foreign=allow_foreign)


def load_issues(repo: str) -> dict[str, dict[str, object]]:
    raw = run_gh(
        "issue",
        "list",
        "--repo",
        repo,
        "--state",
        "all",
        "--limit",
        "1000",
        "--json",
        "number,title,state,url,body",
    )
    issues = json.loads(raw)
    by_key: dict[str, dict[str, object]] = {}
    for issue in issues:
        body = str(issue.get("body") or "")
        match = ROADMAP_MARKER_RE.search(body)
        if match:
            by_key.setdefault(match.group("id"), issue)
        by_key.setdefault(f"title:{issue['title']}", issue)
    return by_key


def find_issue(
    existing: dict[str, dict[str, object]],
    task: Task,
) -> dict[str, object] | None:
    """Prefer the stable roadmap marker, falling back to the issue title."""
    return existing.get(task.id) or existing.get(f"title:{issue_title(task)}")


def known_numbers(
    tasks: list[Task],
    existing: dict[str, dict[str, object]],
) -> dict[str, int]:
    numbers: dict[str, int] = {}
    for task in tasks:
        issue = find_issue(existing, task)
        if issue is not None:
            numbers[task.id] = int(str(issue["number"]))
    return numbers


def ensure_labels(repo: str, phases: set[int]) -> None:
    raw = run_gh("label", "list", "--repo", repo, "--limit", "200", "--json", "name")
    existing = {str(label["name"]) for label in json.loads(raw)}
    wanted = {"roadmap"} | {f"phase-{phase}" for phase in phases}
    for name in sorted(wanted):
        if name in existing:
            continue
        if name == "roadmap":
            color = LABEL_COLOR
            description = "Mirrors a docs/ROADMAP.md task"
        else:
            phase = int(name.removeprefix("phase-"))
            color = PHASE_COLORS[phase % len(PHASE_COLORS)]
            description = f"Phase {phase} work"
        run_gh(
            "label",
            "create",
            name,
            "--repo",
            repo,
            "--color",
            color,
            "--description",
            description,
        )


def sync_issues(
    tasks: list[Task],
    repo: str,
    repo_url: str,
    *,
    update: bool,
    phase_filter: int | None,
) -> dict[str, int]:
    existing = load_issues(repo)
    numbers = known_numbers(tasks, existing)
    pending = [task for task in tasks if not task.done]
    if phase_filter is not None:
        pending = [task for task in pending if task.phase == phase_filter]

    for task in pending:
        title = issue_title(task)
        issue = find_issue(existing, task)
        if issue is not None:
            number = int(str(issue["number"]))
            if update:
                run_gh(
                    "issue",
                    "edit",
                    str(number),
                    "--repo",
                    repo,
                    "--title",
                    title,
                    "--body",
                    issue_body(task, repo_url),
                    "--add-label",
                    f"phase-{task.phase}",
                )
                print(f"updated #{number}: {title}")
            continue

        url = run_gh(
            "issue",
            "create",
            "--repo",
            repo,
            "--title",
            title,
            "--body",
            issue_body(task, repo_url),
            "--label",
            "roadmap",
            "--label",
            f"phase-{task.phase}",
        )
        number = int(url.rstrip("/").rsplit("/", 1)[-1])
        numbers[task.id] = number
        print(f"created #{number}: {title}")

    return numbers


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", help="GitHub repository as owner/repo (default: origin remote)")
    parser.add_argument("--phase", type=int, help="only create/update issues of this phase")
    parser.add_argument(
        "--dry-run", action="store_true", help="print actions without changing GitHub"
    )
    parser.add_argument(
        "--update",
        action="store_true",
        help="replace the body of existing issues with the roadmap text",
    )
    parser.add_argument(
        "--allow-foreign-repo",
        action="store_true",
        help="allow --repo to point to a repository other than origin",
    )
    args = parser.parse_args(argv)

    try:
        tasks = parse_roadmap(ROADMAP.read_text(encoding="utf-8"))
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if not tasks:
        print("error: no roadmap tasks found", file=sys.stderr)
        return 1

    try:
        repo = get_repo_slug(args.repo, allow_foreign=args.allow_foreign_repo)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    repo_url = f"https://github.com/{repo}"

    try:
        if args.dry_run:
            existing = load_issues(repo)
            numbers = known_numbers(tasks, existing)
            print(f"repository: {repo}")
            print(f"tasks: {len(tasks)} ({sum(not task.done for task in tasks)} pending)")
            print("existing issues:", len(numbers))
            for task in tasks:
                if task.done:
                    continue
                if args.phase is not None and task.phase != args.phase:
                    continue
                state = "exists" if task.id in numbers else "missing"
                print(f"  {task.id}: {state}")
            return 0

        target_tasks = [
            task
            for task in tasks
            if not task.done and (args.phase is None or task.phase == args.phase)
        ]
        ensure_labels(repo, {task.phase for task in target_tasks})
        numbers = sync_issues(
            tasks,
            repo,
            repo_url,
            update=args.update,
            phase_filter=args.phase,
        )
    except subprocess.CalledProcessError as exc:
        detail = (exc.stderr or "").strip() or str(exc)
        print(f"error: gh failed: {detail}", file=sys.stderr)
        return 1

    ISSUES_DOC.write_text(
        render_issues_doc(tasks, numbers, repo_url),
        encoding="utf-8",
    )
    print(f"wrote {ISSUES_DOC.relative_to(ROOT)} ({len(numbers)} issues linked)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
